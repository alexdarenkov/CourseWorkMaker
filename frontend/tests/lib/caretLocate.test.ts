/**
 * Поиск места каретки в готовом превью (lib/caretLocate.ts): в какой элемент
 * вывода и в какое место его текста попадает каретка из данной строки и
 * колонки markdown.
 *
 * Пункт спеки для каретки в превью ещё не заведён — когда появится, ID нужно
 * проставить в названия describe.
 *
 * Раскладку happy-dom не считает, но разметку и текст — да, поэтому именно
 * здесь ловится главная ошибка: «каретка не на своём месте», то есть выбран
 * не тот элемент или не то смещение.
 */
import { beforeEach, describe, expect, it } from 'vitest'
import { byLine, locateCaret } from '../../src/lib/caretLocate'
import { renderAll } from '../../src/lib/gostRender'
import { parseMD } from '../../src/lib/markdown'
import { DEFAULT_SETTINGS } from '../../src/lib/settings'

const MD = [
  '# Раздел работы', // 0
  '', // 1
  'Первая строка абзаца.', // 2
  'Вторая строка абзаца.', // 3
  '', // 4
  'Таблица: Сравнение', // 5
  '| Альфа | Бета |', // 6
  '|---|---|', // 7
  '| один | два |', // 8
  '', // 9
  'Рисунок: Схема работы', // 10
  '```mermaid', // 11
  'flowchart LR', // 12
  '  A[Начало] --> B[Процесс]', // 13
  '```', // 14
  '', // 15
  '- первый пункт', // 16
  '- второй пункт', // 17
  '', // 18
  '```python', // 19
  'x = 1', // 20
  'print(x)', // 21
  '```', // 22
  '', // 23
  '$$E = mc^2$$', // 24
  'где E — энергия', // 25
  '', // 26
  'Оценка $\\hat{\\beta}$ состоятельна.', // 27
  '', // 28
  '$$\\hat{\\boldsymbol{\\beta}} = (\\mathbf{X}^\\top \\mathbf{X})^{-1} \\mathbf{X}^\\top \\mathbf{y}$$', // 29
].join('\n')

// Схему рисует mermaid — в тестовой среде её нет, поэтому подставляем SVG той
// же формы, что даёт mermaid с htmlLabels:false (подписи узлов — в tspan).
const FAKE_SVG =
  '<svg viewBox="0 0 300 100">' +
  '<g class="node"><text><tspan>Начало</tspan></text></g>' +
  '<g class="node"><text><tspan>Процесс</tspan></text></g>' +
  '</svg>'

const LINES = MD.split('\n')
const BLOCKS = parseMD(MD)

let strip: HTMLElement

beforeEach(() => {
  // Лента превью: страница со всеми фрагментами (раскладка не важна — важны
  // разметка и текст).
  const { out } = renderAll(BLOCKS, DEFAULT_SETTINGS, () => FAKE_SVG)
  document.body.innerHTML = '<div id="strip"><div data-page="0"></div></div>'
  strip = document.getElementById('strip') as HTMLElement
  ;(strip.firstElementChild as HTMLElement).innerHTML = out.map((b) => b.html).join('')
})

/**
 * Текст найденного места с отметкой «|» на позиции каретки. Если каретка
 * относится к объекту целиком (формула, картинка, схема) — текст в скобках.
 */
function marked(line: number, col: number): string {
  const spot = locateCaret(strip, BLOCKS, LINES, line, col)
  if (!spot) return '<не найдено>'
  if (!spot.node) return '[' + (spot.el.textContent || '') + ']'
  const text = spot.node.data
  const off = spot.offset ?? 0
  return text.slice(0, off) + '|' + text.slice(off)
}

/** Символ вывода, ПЕРЕД которым встала каретка. */
function glyph(line: number, col: number): string {
  const spot = locateCaret(strip, BLOCKS, LINES, line, col)
  if (!spot?.node) return '<символа нет>'
  return spot.node.data[spot.offset ?? 0] ?? '<конец>'
}

describe('caretLocate: текстовые блоки', () => {
  it('в заголовке каретка встаёт после тех же букв, что и в редакторе', () => {
    // «# Раздел работы», каретка после «Разд» (колонка 6).
    expect(marked(0, 6)).toBe('1\u00a0Разд|ел работы')
  })

  it('в абзаце — по колонке', () => {
    expect(marked(2, 6)).toBe('Первая| строка абзаца.')
  })

  it('вторая строка абзаца не сдвигает каретку на первую', () => {
    // Строки абзаца склеены <br>: в тексте разделителя нет, и смещение
    // второй строки отсчитывается от конца первой.
    expect(marked(3, 6)).toBe('Вторая| строка абзаца.')
  })

  it('пункт перечисления адресуется своей строкой, а не началом списка', () => {
    // «- второй пункт»: колонка 8 — сразу за словом «второй».
    expect(marked(17, 8)).toBe('–\u00a0второй| пункт')
  })
})

describe('caretLocate: таблица', () => {
  it('каретка в ячейке заголовка попадает в эту ячейку', () => {
    // «| Альфа | Бета |», колонка 5 — после «Аль».
    expect(marked(6, 5)).toBe('Аль|фа')
  })

  it('каретка во второй колонке — во второй ячейке', () => {
    // «| Альфа | Бета |»: колонка 13 — после «Бет».
    expect(marked(6, 13)).toBe('Бет|а')
  })

  it('строка тела таблицы — своя строка исходника', () => {
    expect(marked(8, 6)).toBe('один|')
  })

  it('подпись таблицы адресуется своей строкой', () => {
    // «Таблица: Сравнение», каретка после «Сравн» (колонка 14).
    expect(marked(5, 14)).toBe('Таблица 1 – Сравн|ение')
  })

  it('строка-разделитель «|---|» каретку не теряет', () => {
    expect(marked(7, 2)).not.toBe('<не найдено>')
  })
})

describe('caretLocate: рисунок, схема, формула', () => {
  it('подпись рисунка адресуется своей строкой', () => {
    // «Рисунок: Схема работы», каретка после «Схема» (колонка 14).
    expect(marked(10, 14)).toBe('Рисунок 1 – Схема| работы')
  })

  it('каретка в подписи узла схемы попадает в эту подпись', () => {
    // «  A[Начало] --> B[Процесс]»: колонка 7 — после «Нач» внутри подписи.
    expect(marked(13, 7)).toBe('Нач|ало')
  })

  it('каретка во второй подписи попадает во вторую', () => {
    // Колонка 23 — после «Проце» во втором узле.
    expect(marked(13, 23)).toBe('Проце|сс')
  })

  it('в синтаксисе схемы (стрелка) каретка встаёт к самой схеме', () => {
    // Колонка 13 — на «-->», подписи там нет.
    expect(locateCaret(strip, BLOCKS, LINES, 13, 13)!.node).toBeUndefined()
  })

  it('в выключной формуле каретка встаёт на её символ', () => {
    // «$$E = mc^2$$»: колонка 6 — перед «m», в выводе это третий символ.
    expect(glyph(24, 6)).toBe('m')
    // Колонка 9 — перед степенью «2».
    expect(glyph(24, 9)).toBe('2')
  })

  it('пояснение «где …» адресуется своей строкой, а не строкой формулы', () => {
    // Раньше пояснение метилось строкой формулы, и каретка на нём исчезала.
    expect(marked(25, 8)).toBe('где E \u2013 |энергия')
  })
})

describe('caretLocate: листинг', () => {
  it('вторая строка кода отсчитывается от первой вместе с переносом', () => {
    // В листинге строки склеены НАСТОЯЩИМ переносом — он символ текста.
    expect(marked(21, 5)).toBe('x = 1\nprint|(x)')
  })

  it('ограждение листинга ставит каретку в начало кода', () => {
    expect(marked(19, 2)).toBe('|x = 1\nprint(x)')
  })
})

describe('caretLocate: служебное', () => {
  it('метка строки находит все фрагменты блока в порядке документа', () => {
    expect(byLine(strip, 2)).toHaveLength(1)
    expect(byLine(strip, undefined)).toEqual([])
  })

  it('на стыке строк абзаца каретка уходит в начало следующей', () => {
    // Колонка 0 второй строки: позиция ровно на границе текстовых узлов —
    // каретка должна встать в начало второй строки, а не в конец первой.
    expect(marked(3, 0)).toBe('|Вторая строка абзаца.')
  })
})

describe('caretLocate: строчная формула в абзаце', () => {
  // Строка 27: «Оценка $\hat{\beta}$ состоятельна.»
  it('каретка ВНУТРИ формулы встаёт на её символ, а не на всю формулу', () => {
    // KaTeX кладёт в вывод и глифы, и скрытую копию MathML с исходным LaTeX;
    // раньше смещение попадало в эту скрытую копию, и каретка улетала.
    const spot = locateCaret(strip, BLOCKS, LINES, 27, 12)!
    expect(spot.el.classList.contains('katex')).toBe(true)
    expect(spot.node).toBeDefined()
    // Скрытая копия формулы кареткой не адресуется.
    expect(spot.node!.parentElement!.closest('.katex-mathml')).toBeNull()
  })

  it('каретка ДО формулы стоит в обычном тексте', () => {
    expect(marked(27, 3)).toBe('Оце|нка ')
  })

  it('каретка ПОСЛЕ формулы не съезжает на её длину в исходнике', () => {
    // В исходнике формула занимает 14 символов, в выводе — пару глифов:
    // смещение считается по обычным символам, формулы пропускаются целиком.
    // Колонка 22 — после «с» слова «состоятельна».
    expect(marked(27, 22)).toBe(' с|остоятельна.')
  })
})

describe('caretLocate: большая выключная формула', () => {
  // Строка 29: «$$\hat{\boldsymbol{\beta}} = (\mathbf{X}^\top …$$»
  // В выводе KaTeX: β ^ = ( X ⊤ X ) − 1 X ⊤ y
  const BIG = () => LINES[29]

  it('каретка идёт по формуле вместе с исходником, а не стоит перед ней', () => {
    // Сразу за «(\mathbf{X}» — то есть перед знаком транспонирования.
    expect(glyph(29, BIG().indexOf('^\\top'))).toBe('⊤')
    // Перед закрывающей скобкой группы.
    expect(glyph(29, BIG().indexOf(')^{-1}'))).toBe(')')
    // Внутри степени «−1»: перед единицей.
    expect(glyph(29, BIG().indexOf('1}'))).toBe('1')
  })

  it('в начале формулы каретка на первом символе, в конце — на последнем', () => {
    expect(glyph(29, 2)).toBe('β')
    expect(glyph(29, BIG().indexOf('\\mathbf{y}'))).toBe('y')
  })

  it('каретка внутри формулы не попадает в скрытую копию MathML', () => {
    const spot = locateCaret(strip, BLOCKS, LINES, 29, 30)!
    expect(spot.node!.parentElement!.closest('.katex-mathml')).toBeNull()
  })
})
